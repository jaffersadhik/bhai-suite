package com.suite.security;

import java.util.HashMap;
import java.util.Map;

/** 5 x 7 dot-matrix letters for the captcha. Only look-alike-free symbols (no 0/O, 1/I, 5/S, 2/Z, 8/B, G/6 ...). */
final class Glyphs {
    /** the symbols a captcha may contain (24): easy to read and to type on a phone */
    static final String ALPHABET = "ACDEFHJKLMNPRTUWXY234679";

    private static final Map<Character, String[]> G = new HashMap<>();

    private static void g(char c, String... rows) {
        if (rows.length != 7) throw new IllegalStateException("glyph " + c);
        G.put(c, rows);
    }

    static {
        g('A', ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
        g('C', ".####", "#....", "#....", "#....", "#....", "#....", ".####");
        g('D', "####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####.");
        g('E', "#####", "#....", "#....", "####.", "#....", "#....", "#####");
        g('F', "#####", "#....", "#....", "####.", "#....", "#....", "#....");
        g('H', "#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
        g('J', "..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##..");
        g('K', "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#");
        g('L', "#....", "#....", "#....", "#....", "#....", "#....", "#####");
        g('M', "#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#");
        g('N', "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#");
        g('P', "####.", "#...#", "#...#", "####.", "#....", "#....", "#....");
        g('R', "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#");
        g('T', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..");
        g('U', "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.");
        g('W', "#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#");
        g('X', "#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#");
        g('Y', "#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#..");
        g('2', ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####");
        g('3', "####.", "....#", "....#", ".###.", "....#", "....#", "####.");
        g('4', "...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#.");
        g('6', ".###.", "#....", "#....", "####.", "#...#", "#...#", ".###.");
        g('7', "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#...");
        g('9', ".###.", "#...#", "#...#", ".####", "....#", "....#", ".###.");
        for (char c : ALPHABET.toCharArray()) if (!G.containsKey(c)) throw new IllegalStateException("missing glyph " + c);
    }

    static String[] of(char c) {
        return G.get(c);
    }

    private Glyphs() {
    }
}
